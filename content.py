def fortune_for(d: date = None, salt: str = ""):
    """同一天同一用户结果固定"""
    d = d or date.today()
    seed = int(hashlib.md5(f"{d.isoformat()}|{salt}|vesna".encode()).hexdigest()[:12], 16)
    rng = random.Random(seed)
    tiers = [t[0] for t in TIERS]
    tier = rng.choices(tiers, [t[1] for t in TIERS])[0]
    color = dict((t[0], t[2]) for t in TIERS)[tier]
    stars = {"大吉": 5, "中吉": 4, "小吉": 4, "吉": 3, "末吉": 2, "凶": 1}[tier]
    good = rng.sample(GOOD, 2)
    bad = rng.sample(BAD, 2)
    lc = rng.choice(COLORS)
    return dict(date=d.isoformat(), tier=tier, tier_color=color, stars=stars, good=good, bad=bad,
                lucky_color=lc, lucky_item=rng.choice(ITEMS), lucky_num=rng.randint(1, 99), word=TIER_WORDS[tier])


