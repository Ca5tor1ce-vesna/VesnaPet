# ---------------- 好感等级 ----------------
LEVELS = [(0, "初识"), (50, "熟悉"), (150, "朋友"), (350, "好友"), (700, "挚友"), (1200, "心之契约")]


def level_info(points):
    """返回 (等级序号 1.., 名称, 本级起点, 下一级起点或 None)"""
    idx = 0
    for i, (th, _) in enumerate(LEVELS):
        if points >= th:
            idx = i
    nxt = LEVELS[idx + 1][0] if idx + 1 < len(LEVELS) else None
    return idx + 1, LEVELS[idx][1], LEVELS[idx][0], nxt


